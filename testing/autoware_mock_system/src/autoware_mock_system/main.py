import rclpy
from rclpy.executors import ExternalShutdownException
from rclpy.node import Node

from .modules.operation_mode import OperationMode


class SystemMock(Node):
    def __init__(self):
        super().__init__("system_mock")
        self.operation_mode = OperationMode(self)


def main(args=None):
    rclpy.init(args=args)
    node = None
    try:
        node = SystemMock()
        rclpy.spin(node)
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        if node is not None:
            node.destroy_node()
        rclpy.try_shutdown()


if __name__ == "__main__":
    main()
